"""Refreshes web/src/lib/ipc.ts: INDEC's consumer price index (IPC, Nivel general, Total
nacional, base Dec 2016 = 100), used by the "Informe para la asamblea" page to compare
spending with inflation. Public data, committed to the repo; run `make ipc` after INDEC
publishes a month (around the 13th of the next month).

Source: the national time-series API (apis.datos.gob.ar, Ministerio de Economía), which
republishes INDEC's series 148.3_INIVELNAL_DICI_M_26. Nothing about the consortium is sent.
"""

from __future__ import annotations

import json
import urllib.request
from pathlib import Path

from .config import REPO, WEB

SERIES_ID = "148.3_INIVELNAL_DICI_M_26"
URL = f"https://apis.datos.gob.ar/series/api/series/?ids={SERIES_ID}&start_date=2024-01-01&format=json&limit=1000"
OUT = WEB / "src" / "lib" / "ipc.ts"


def parse(payload: dict) -> dict[str, float]:
    """{'YYYY-MM': index}; fails on a gap or a non-positive value (never publish a broken series)."""
    out: dict[str, float] = {}
    for fecha, valor in payload["data"]:
        if valor is None:
            continue
        if not isinstance(valor, int | float) or valor <= 0:
            raise ValueError(f"IPC {fecha}: bad value {valor!r}")
        out[fecha[:7]] = round(float(valor), 4)
    months = sorted(out)
    for a, b in zip(months, months[1:], strict=False):
        y, m = map(int, a.split("-"))
        nxt = f"{y + (m == 12)}-{m % 12 + 1:02d}"
        if b != nxt:
            raise ValueError(f"IPC: gap between {a} and {b}")
    return out


def render(series: dict[str, float]) -> str:
    rows = "\n".join(f'  "{k}": {v},' for k, v in sorted(series.items()))
    return f"""// GENERATED by `make ipc` (pipeline/alas3/ipc.py). Do not edit by hand.
// INDEC, IPC Nivel general, Total nacional, base diciembre 2016 = 100 (series {SERIES_ID},
// via apis.datos.gob.ar). Public data; refresh after INDEC publishes each month.
export const IPC: Record<string, number> = {{
{rows}
}};
"""


def update(out: Path = OUT) -> dict[str, float]:
    req = urllib.request.Request(URL, headers={"User-Agent": "alas3-portal"})
    with urllib.request.urlopen(req, timeout=30) as r:  # noqa: S310 (fixed https URL)
        series = parse(json.load(r))
    out.write_text(render(series))
    print(f"IPC: {len(series)} months, up to {max(series)} -> {out.relative_to(REPO)}")
    return series

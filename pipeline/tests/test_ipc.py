import pytest

from alas3 import ipc


def test_parse_and_render():
    series = ipc.parse({"data": [["2025-11-01", 9841.3581], ["2025-12-01", 10121.37151], ["2026-01-01", None]]})
    assert series == {"2025-11": 9841.3581, "2025-12": 10121.3715}
    ts = ipc.render(series)
    assert '"2025-12": 10121.3715,' in ts and "GENERATED" in ts


def test_parse_fails_closed():
    with pytest.raises(ValueError, match="gap"):
        ipc.parse({"data": [["2025-11-01", 1.0], ["2026-01-01", 2.0]]})
    with pytest.raises(ValueError, match="bad value"):
        ipc.parse({"data": [["2025-11-01", -1]]})


def test_committed_table_is_well_formed():
    from alas3.config import WEB

    text = (WEB / "src/lib/ipc.ts").read_text()
    assert text.startswith("// GENERATED by `make ipc`")
